#!/usr/bin/env python3
"""Generates the frozen scenario list (ADR-0009). Output: lab/scenarios/list.toml

The legitimate-workload section at the end of list.toml is appended manually;
this generator emits only the 100 attack scenarios.
"""
classes = {
    "cloud_credentials": "T1552.001", "ssh_key": "T1552.004", "env": "T1552.001",
    "llm_keys": "T1552.001", "mcp_config": "T1552.001",
    "database_dump": "T1005", "ai_note": "T1005",
    "bash_history": "T1552.003", "known_hosts": "T1083", "ssh_config": "T1083",
}
methods = ["cat", "head", "grep", "cp", "dd", "base64", "python3", "tar", "awk", "xargs"]
contexts = ["human", "ai-claude", "ai-mcp", "script", "container"]
lines = ["# Frozen scenario list (ADR-0009). Not changed after measurement.",
         "# Generated by: tools/scenario-list-gen.py (deterministic).", ""]
selected = []
class_names = list(classes)
for s_idx, cls in enumerate(class_names):
    for y_idx, method in enumerate(methods):
        context = contexts[(s_idx + y_idx) % len(contexts)]
        selected.append((cls, method, context))
# 10 classes x 10 methods = 100; guarantee the container and AI distribution:
output = []
for n, (cls, method, context) in enumerate(selected, 1):
    output.append((n, cls, method, context))
for n, cls, method, context in output:
    lines.append("[[scenario]]")
    lines.append(f'id = "S{n:03d}"')
    lines.append(f'class = "{cls}"')
    lines.append(f'method = "{method}"')
    lines.append(f'context = "{context}"')
    lines.append(f'technique = "{classes[cls]}"')
    lines.append('expected = "finding"')
    lines.append("")
print("\n".join(lines))
