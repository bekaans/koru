#!/usr/bin/env python3
"""Generates the MITRE ATT&CK Enterprise technique catalog (koru-detect) from the
official STIX bundle.

Usage:
    python3 tools/attack-catalog-gen.py <enterprise-attack-VERSION.json> <expected-sha256> > \
        crates/koru-detect/data/attack-enterprise-vVERSION.tsv

The input is the `enterprise-attack/enterprise-attack-VERSION.json` file at tag vVERSION of
the mitre-attack/attack-stix-data repo (for example 20.0). The script never touches
the network; download the file by hand and pass its SHA-256 digest (docs/architecture.md#toolchain-and-versions) as
the second argument. If the digest does not match, no output is produced.

Output format (tab-separated; lines starting with `#` are comments):
    tactic     <id>  <short name>  <name>
    technique  <id>  <status>      <tactics (comma-joined)>  <name>  <replaced-by (comma-joined)>
Status: current | revoked (replaced-by holds the revoked-by targets) | deprecated.
"""

import hashlib
import json
import sys


def mitre_id(obj):
    for r in obj.get("external_references", []):
        if r.get("source_name") == "mitre-attack":
            return r.get("external_id")
    return None


def clean(text):
    return " ".join(str(text).replace("\t", " ").split())


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    path, expected = sys.argv[1], sys.argv[2].lower()
    with open(path, "rb") as f:
        data = f.read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != expected:
        sys.exit(f"SHA-256 mismatch: {digest} != {expected}")
    bundle = json.loads(data)
    objects = bundle["objects"]
    by_id = {n["id"]: n for n in objects if "id" in n}
    collection = [n for n in objects if n.get("type") == "x-mitre-collection"]
    version = collection[0].get("x_mitre_version") if collection else "?"

    replaced_by = {}
    for n in objects:
        if n.get("type") == "relationship" and n.get("relationship_type") == "revoked-by":
            target = by_id.get(n.get("target_ref"))
            if target is not None and mitre_id(target):
                replaced_by.setdefault(n["source_ref"], set()).add(mitre_id(target))

    tactics = []
    for n in objects:
        if n.get("type") == "x-mitre-tactic" and not n.get("revoked") and not n.get("x_mitre_deprecated"):
            tactics.append((mitre_id(n), n["x_mitre_shortname"], clean(n["name"])))

    techniques = {}
    for n in objects:
        if n.get("type") != "attack-pattern":
            continue
        tid = mitre_id(n)
        if not tid or not tid.startswith("T"):
            continue
        if n.get("revoked"):
            status = "revoked"
        elif n.get("x_mitre_deprecated"):
            status = "deprecated"
        else:
            status = "current"
        row = (
            tid,
            status,
            ",".join(p["phase_name"] for p in n.get("kill_chain_phases", []) if p.get("kill_chain_name") == "mitre-attack"),
            clean(n.get("name", "")),
            ",".join(sorted(replaced_by.get(n["id"], set()))),
        )
        previous = techniques.get(tid)
        # When several objects share an id, the current one is preferred.
        if previous is None or (previous[1] != "current" and status == "current"):
            techniques[tid] = row

    print(f"# MITRE ATT&CK Enterprise v{version} technique and tactic catalog (koru-detect).")
    print(f"# Source: https://github.com/mitre-attack/attack-stix-data/releases/tag/v{version}")
    print(f"#         enterprise-attack/enterprise-attack-{version}.json")
    print(f"# SHA-256: {digest}")
    print("# Generated by: python3 tools/attack-catalog-gen.py <json> <sha256>; do not edit by hand.")
    print("# Format: tactic<TAB>id<TAB>short name<TAB>name")
    print("#         technique<TAB>id<TAB>status<TAB>tactics<TAB>name<TAB>replaced-by")
    print(f"version\t{version}")
    for tid, short, name in sorted(tactics):
        print(f"tactic\t{tid}\t{short}\t{name}")
    for tid in sorted(techniques):
        k, status, tac, name, rep = techniques[tid]
        print(f"technique\t{k}\t{status}\t{tac}\t{name}\t{rep}")


if __name__ == "__main__":
    main()
