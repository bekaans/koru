#!/usr/bin/env python3
"""Generates the end-to-end metrics report (never edited by hand): docs/reports/metrics.md
Usage: e2e-metrics-gen.py [result-dir]  (default lab/out/scenarios)
Inputs: the result files of the end-to-end suite in the result directory (scenario results,
performance and resilience measurements) and data/golden (the replay outcome is
not taken from test output; the numbers are counted from the golden files)."""
import json
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent
# Result directory: first argument, default lab/out/scenarios (what `lab/lab.sh` writes).
out = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else root / "lab/out/scenarios"
result = json.loads((out / "scenarios-result.json").read_text())
perf_path = out / "performance.json"
perf = json.loads(perf_path.read_text()) if perf_path.exists() else {}
res_path = out / "resilience.json"
res = json.loads(res_path.read_text()) if res_path.exists() else {}

extra_path = out / "extra-new-decoy-result.json"
extra = json.loads(extra_path.read_text()).get("extra_new_decoy", {}) if extra_path.exists() else result.get("extra_new_decoy", {})
s = result["attack"]["results"]
latencies = sorted(r["latency_ms"] for r in s if r["status"] == "PASS")


def fraction(_set, name):
    picked = [r for r in s if r["context"] == name]
    passed = sum(1 for r in picked if r["status"] == "PASS")
    return f"{passed}/{len(picked)}" if picked else "-"


ai = [r for r in s if r["context"] in ("ai-claude", "ai-mcp")]
ai_pass = sum(1 for r in ai if r["status"] == "PASS" and r.get("actor") == "ai_agent")
human = [r for r in s if r["context"] == "human"]
container = [r for r in s if r["context"] == "container"]


def p(q):
    return latencies[min(len(latencies) - 1, int(len(latencies) * q))] if latencies else "-"


lines = [
    "# Koru metrics report (end-to-end suite)",
    "",
    "This file is generated by `tools/e2e-metrics-gen.py`; do not edit it by hand. Sources:",
    "the scenario results, performance and resilience measurements of the end-to-end suite.",
    "",
    "## Detection",
    "",
    f"- Attack scenarios: {result['attack']['passed']}/{result['attack']['total']} caught.",
    f"- MTTD (event -> finding record, driver-measurement upper bound): median {p(0.5)} ms, p95 {p(0.95)} ms, max {latencies[-1] if latencies else '-'} ms.",
    f"- False positives: {result['legit']['finding_count']} findings in the legitimate phase (6 legitimate workloads; 0 in the golden replay).",
    f"- Extra evidence (a new decoy from a data file only): {extra}",
    "",
    "## Catches by actor kind",
    "",
    f"- AI-agent context (claude+mcp chain): {ai_pass}/{len(ai)} caught and the actor marked `ai_agent`.",
    f"- Human context: {sum(1 for r in human if r['status'] == 'PASS')}/{len(human)} caught.",
    f"- Container context: {sum(1 for r in container if r['status'] == 'PASS')}/{len(container)} caught.",
    "",
    "## Performance (4 vCPU lab VM, under the reference load)",
    "",
]
if perf:
    lines += [
        f"- CPU: {perf.get('cpu_total_capacity_pct')}% of total capacity (single core {perf.get('cpu_single_core_pct')}%); budget <2%.",
        f"- Peak RAM (VmHWM): {perf.get('rss_peak_mb')} MB; budget <100 MB.",
        f"- Notification latency: {perf.get('notifications_matched')}/{perf.get('access_count')} accesses matched, p95 {perf.get('latency_p95_s')} s; budget <5 s.",
    ]
else:
    lines.append("- (waiting for performance.json)")
lines += ["", "## Resilience", ""]
if res:
    for name, v in res.items():
        lines.append(f"- {name}: {v.get('status')}")
else:
    lines.append("- (waiting for resilience.json)")
lines.append("")
(root / "docs/reports/metrics.md").write_text("\n".join(lines))
print("docs/reports/metrics.md written")
